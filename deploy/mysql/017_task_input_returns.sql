CREATE TABLE IF NOT EXISTS task_input_returns (
  return_id VARCHAR(96) NOT NULL PRIMARY KEY,
  conversation_id VARCHAR(96) NOT NULL,
  source_task_id VARCHAR(96) NOT NULL,
  source_investigation_id VARCHAR(96) NOT NULL,
  source_command_id VARCHAR(256) NOT NULL,
  trigger_id VARCHAR(96) NOT NULL,
  origin_investigation_id VARCHAR(96) NOT NULL,
  origin_command_id VARCHAR(256) NOT NULL,
  content_sha256 CHAR(64) NOT NULL,
  reason TEXT NOT NULL,
  state VARCHAR(16) NOT NULL,
  revision BIGINT NOT NULL,
  target_investigation_id VARCHAR(96) NULL,
  target_command_id VARCHAR(256) NULL,
  decision_json JSON NULL,
  created_at TIMESTAMP(6) NOT NULL,
  updated_at TIMESTAMP(6) NOT NULL,
  UNIQUE KEY uq_input_return_source (source_investigation_id,source_command_id),
  UNIQUE KEY uq_input_return_target (target_investigation_id,target_command_id),
  KEY ix_input_returns_pending (conversation_id,state,created_at,return_id),
  KEY ix_input_returns_origin (trigger_id,source_task_id),
  FOREIGN KEY (conversation_id) REFERENCES investigations(investigation_id),
  FOREIGN KEY (source_investigation_id) REFERENCES investigations(investigation_id),
  FOREIGN KEY (origin_investigation_id) REFERENCES investigations(investigation_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin;
